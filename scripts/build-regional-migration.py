"""Render the regional selection migration from the shared JSON policy."""
import json
import sys
from pathlib import Path

policy = json.loads(Path('data/learning/selection-policy.json').read_text())
facts = json.loads(Path('data/learning/countries.json').read_text())
policy['countryContinents'] = {
    iso: policy['continentOverrides'].get(iso, policy['subregionContinents'][fact['subregion']])
    for iso, fact in facts.items()
}
config = json.dumps(policy, ensure_ascii=False, separators=(',', ':'))
helpers = Path('scripts/population/selection-helpers.sql').read_text()
start = helpers.index('create or replace function game.pick_balanced_question')
end = helpers.index('revoke all on function game.selection_policy', start)
wrapper = helpers[start:end]
marker = ' with recent as ('
assert wrapper.count(marker) == 1
wrapper = wrapper.replace(marker, """ if (cfg->'regionalAfricaTargets') ? p_category then
  return game.pick_regional_question(p_category,p_difficulty,p_room,p_excluded);
 end if;
""" + marker)
Path(sys.argv[1]).write_text(
    "-- Generated by scripts/build-regional-migration.py.\n"
    "create or replace function game.selection_policy() returns jsonb\n"
    "language sql immutable security invoker set search_path='' as $config$\n"
    f"select $policy${config}$policy$::jsonb\n$config$;\n"
    + Path('scripts/regional-selection.sql').read_text()
    + wrapper
)
