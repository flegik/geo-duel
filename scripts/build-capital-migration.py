"""Render an atomic capital question replacement, keeping predecessor rows intact."""
import json
import sys
from pathlib import Path

questions = json.loads(Path('data/question-pool/capitals.json').read_text())
rows = []
for q in questions:
    if not q['id'].startswith('capital-cities-v1-'):
        continue
    p = q['provenance']
    rows.append([q['id'], p['replaces'], q['difficulty'], q['prompt'], q['options'], q['correct'],
                 q['explanation'], p['sources'], p['confusions'], p['capitalOptions']])
blob = json.dumps(rows, ensure_ascii=False, separators=(',', ':'))
assert '$seed$' not in blob
sql = """-- Generated by scripts/build-capital-migration.py.
-- Match assignments, option order, recorded answers and prior question text are untouched.
do $migration$
declare
 payload jsonb := $seed$@@ROWS@@$seed$::jsonb;
 expected_count int := jsonb_array_length(payload);
 verified int;
begin
 create temporary table capital_changes on commit drop as
 select row->>0 as id, old.id as predecessor, old.category, (row->>2)::int as difficulty,
  row->>3 as prompt, row->4 as options, (row->>5)::int as correct,
  row->>6 as explanation, old.media,
  old.provenance||jsonb_build_object('edition','capital-cities-2026-11','replaces',old.id,
   'sources',row->7,'confusions',row->8,'capitalOptions',row->9) as provenance
 from jsonb_array_elements(payload) seed(row)
 join game.questions old on old.id=row->>1
 where old.category='capitals' and old.subject_key like 'capital:%';

 if (select count(*) from capital_changes)<>expected_count then
  raise exception 'Capital predecessors are missing';
 end if;
 insert into game.questions(id,category,difficulty,prompt,options,correct,explanation,media,provenance,enabled)
 select id,category,difficulty,prompt,options,correct,explanation,media,provenance,false
 from capital_changes on conflict(id) do nothing;

 select count(*) into verified
 from capital_changes e join game.questions q using(id)
 where (q.category,q.difficulty,q.prompt,q.options,q.correct,q.explanation,q.media,q.provenance,q.subject_key)
  is not distinct from
  (e.category,e.difficulty,e.prompt,e.options,e.correct,e.explanation,e.media,e.provenance,e.provenance->>'subjectKey');
 if verified<>expected_count then raise exception 'Capital data mismatches'; end if;

 update game.questions q set enabled=coalesce(q.id=e.id,false)
 from (select id,id as affected from capital_changes union select null,predecessor from capital_changes) e
 where q.id=e.affected and q.enabled is distinct from coalesce(q.id=e.id,false);
end
$migration$;
"""
Path(sys.argv[1]).write_text(sql.replace('@@ROWS@@', blob))
